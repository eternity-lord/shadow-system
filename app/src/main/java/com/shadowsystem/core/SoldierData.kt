    val byKey: Map<String, SoldierDef> = ALL.associateBy { it.key }

    fun voiceLine(key: String, stage: Int, index: Int): String {
        val def = byKey[key] ?: return ""
        val linesForStage = def.voiceLines[stage] ?: def.voiceLines[1] ?: return ""
        if (linesForStage.isEmpty()) return ""
        return linesForStage[index % linesForStage.size]
    }
